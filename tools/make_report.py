def _dvh_svg(dvh):
    if not HAS_MPL or not dvh.get("bins"):
        return "<p><i>DVH chart unavailable</i></p>"
    fig, ax = plt.subplots(figsize=(8, 4.5), dpi=96)
    b = np.array(dvh["bins"]); v = np.array(dvh["volumes"]) * 100
    ax.fill_between(b, v, alpha=.3, color="#2196F3")
    ax.plot(b, v, color="#1976D2", lw=2)
    ax.axhline(95, ls="--", c="#F44336", lw=1)
    ax.set_xlabel("Dose (rel.)"); ax.set_ylabel("Volume (%)")
    ax.set_title("Dose-Volume Histogram"); ax.grid(alpha=.3)
    buf = io.BytesIO(); fig.savefig(buf, format="svg", bbox_inches="tight")
    plt.close(fig); buf.seek(0)
    return buf.getvalue().decode("utf-8")


